CREATE SCHEMA shop;
CREATE TABLE shop.customers (
  customer_id integer GENERATED BY DEFAULT
              AS IDENTITY PRIMARY KEY,
  full_name   varchar(100) NOT NULL,
  email       varchar(150),
  city        varchar(60),
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamp(0) NOT NULL DEFAULT now());
CREATE TABLE shop.orders (
  order_id     bigint GENERATED BY DEFAULT
               AS IDENTITY PRIMARY KEY,
  customer_id  integer NOT NULL
               REFERENCES shop.customers,
  order_date   timestamp(0) NOT NULL,
  status       varchar(12) NOT NULL CHECK (status IN
                 ('NEW','SHIPPED','CANCELLED')),
  total_amount numeric(10,2) NOT NULL,
  notes        text);
CREATE INDEX orders_cust_ix ON shop.orders (customer_id);
