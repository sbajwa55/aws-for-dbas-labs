CREATE USER shop IDENTIFIED BY "<LAB_PASSWORD>"
  DEFAULT TABLESPACE users QUOTA 200M ON users;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW
  TO shop;
CREATE TABLE shop.customers (
  customer_id NUMBER(10) GENERATED BY DEFAULT
              AS IDENTITY PRIMARY KEY,
  full_name   VARCHAR2(100) NOT NULL,
  email       VARCHAR2(150),
  city        VARCHAR2(60),
  is_active   NUMBER(1) DEFAULT 1 NOT NULL
              CHECK (is_active IN (0,1)),
  created_at  DATE DEFAULT SYSDATE NOT NULL);
CREATE TABLE shop.orders (
  order_id     NUMBER(19) GENERATED BY DEFAULT
               AS IDENTITY PRIMARY KEY,
  customer_id  NUMBER(10) NOT NULL
               REFERENCES shop.customers,
  order_date   DATE NOT NULL,
  status       VARCHAR2(12) NOT NULL
               CHECK (status IN
                 ('NEW','SHIPPED','CANCELLED')),
  total_amount NUMBER(10,2) NOT NULL,
  notes        VARCHAR2(4000));
CREATE VIEW shop.recent_orders AS
SELECT o.order_id, c.full_name, o.order_date,
       o.total_amount
FROM shop.orders o JOIN shop.customers c
  USING (customer_id)
WHERE o.order_date >= TIMESTAMP '2025-02-01 00:00:00'
ORDER BY o.order_date DESC
FETCH FIRST 100 ROWS ONLY;
EXIT
