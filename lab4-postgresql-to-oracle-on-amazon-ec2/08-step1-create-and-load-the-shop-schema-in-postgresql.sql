CREATE VIEW shop.recent_orders AS
SELECT o.order_id, c.full_name, o.order_date,
       o.total_amount
FROM shop.orders o JOIN shop.customers c
  USING (customer_id)
WHERE o.order_date >= timestamp '2025-02-01'
ORDER BY o.order_date DESC
LIMIT 100;
